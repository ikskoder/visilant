/**
 * Build the extension from a copy of the tree, without touching `extension/`.
 *
 *   esno scripts/build-copy.ts <dir> [chrome|firefox]
 *
 * The working tree's `extension/` is whatever the developer has loaded in their
 * own browser, and `pnpm dev` may be writing into it right now. A production
 * build there wipes `dist/` underneath their tabs, and a test run that builds
 * for Firefox and then for Chrome hands a browser that restarts its background
 * in between whichever half-written or wrong build is there at that moment, or
 * reloads the extension under them where a watcher is running. So the sources
 * are copied into `<dir>` and built
 * there, and the build lands in `<dir>/extension` (`<dir>/extension-firefox` for
 * Firefox). The copy is of the working
 * tree, not of a commit: the point is to test the edits not committed yet.
 */

import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'
import process from 'node:process'

const root = path.resolve(__dirname, '..')

// Everything the five vite configs and scripts/prepare.ts read
const ENTRIES = [
  'src',
  'scripts',
  'extension/_locales',
  'extension/assets',
  'package.json',
  'tsconfig.json',
  'unocss.config.ts',
  'modules.d.ts',
  'shim.d.ts',
  'vite.config.mts',
  'vite.config.background.mts',
  'vite.config.content.mts',
  'vite.config.frame.mts',
  'vite.config.clipboard.mts',
]

/** Build into `<dest>/extension` or `<dest>/extension-firefox` and return that directory. */
export function buildCopy(dest: string, browser: 'chrome' | 'firefox' = 'chrome'): string {
  const target = path.resolve(dest)
  // Wiped before the copy, so only a directory inside .tmp/ and never .tmp/
  // itself, which holds the screenshots and every other copy
  if (!path.relative(root, target).startsWith(`.tmp${path.sep}`))
    throw new Error(`refusing to build into ${target}: give a directory under .tmp/`)

  fs.rmSync(target, { recursive: true, force: true })
  fs.mkdirSync(target, { recursive: true })
  for (const entry of ENTRIES) {
    fs.cpSync(path.join(root, entry), path.join(target, entry), {
      recursive: true,
      // Generated by the build, and nested node_modules are pnpm links
      filter: source => !source.includes(`${path.sep}node_modules`),
    })
  }
  fs.symlinkSync(path.join(root, 'node_modules'), path.join(target, 'node_modules'), 'dir')

  const script = browser === 'firefox' ? 'build-firefox' : 'build'
  execFileSync('pnpm', ['run', script], { cwd: target, stdio: 'inherit', env: { ...process.env, NODE_ENV: 'production' } })

  const manifest = path.join(target, browser === 'firefox' ? 'extension-firefox' : 'extension', 'manifest.json')
  if (!fs.existsSync(manifest))
    throw new Error(`the build finished but wrote no ${manifest}`)
  console.log(`Built for ${browser} into ${path.relative(root, path.dirname(manifest))}`)
  return path.dirname(manifest)
}

if (require.main === module) {
  const [dest, browser = 'chrome'] = process.argv.slice(2)
  if (!dest || (browser !== 'chrome' && browser !== 'firefox')) {
    console.error('usage: esno scripts/build-copy.ts <dir under .tmp/> [chrome|firefox]')
    process.exit(1)
  }
  buildCopy(dest, browser)
}
