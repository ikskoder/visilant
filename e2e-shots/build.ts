/**
 * Build the extension for the screenshot run, without touching `extension/`.
 *
 * The working tree's `extension/` is whatever the developer has loaded in their
 * own browser, and `pnpm dev` may be writing into it right now. A production
 * build there would wipe `dist/` underneath their tabs, and a copy taken while
 * the watchers run could be half dev, half prod. So the sources are copied into
 * `.tmp/shots/build-src` and built there. The copy is of the working tree, not
 * of a commit: the point is to see the edits that have not been committed yet.
 */
/* eslint-disable no-console -- a command-line step, and its output is the report */
import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import path from 'node:path'
import process from 'node:process'

const root = path.resolve(__dirname, '..')
const dest = path.join(root, '.tmp/shots/build-src')

// Everything the five vite configs and scripts/prepare.ts read
const ENTRIES = [
  'src',
  'scripts',
  'extension/_locales',
  'extension/assets',
  'package.json',
  'tsconfig.json',
  'unocss.config.ts',
  'modules.d.ts',
  'shim.d.ts',
  'vite.config.mts',
  'vite.config.background.mts',
  'vite.config.content.mts',
  'vite.config.frame.mts',
  'vite.config.clipboard.mts',
]

fs.rmSync(dest, { recursive: true, force: true })
fs.mkdirSync(dest, { recursive: true })
for (const entry of ENTRIES) {
  fs.cpSync(path.join(root, entry), path.join(dest, entry), {
    recursive: true,
    // Generated by the build, and nested node_modules are pnpm links
    filter: source => !source.includes(`${path.sep}node_modules`),
  })
}
fs.symlinkSync(path.join(root, 'node_modules'), path.join(dest, 'node_modules'), 'dir')

execFileSync('pnpm', ['run', 'build'], { cwd: dest, stdio: 'inherit', env: { ...process.env, NODE_ENV: 'production' } })

const manifest = path.join(dest, 'extension/manifest.json')
if (!fs.existsSync(manifest))
  throw new Error(`the build finished but wrote no ${manifest}`)
console.log(`Built into ${path.relative(root, path.dirname(manifest))}`)
